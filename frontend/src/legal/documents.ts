export const LEGAL_DOCUMENTS: LegalDocument[] = [TERMS, PRIVACY, STORAGE];

export function legalDocument(id: LegalDocumentId): LegalDocument {
  const found = LEGAL_DOCUMENTS.find((document) => document.id === id);
  if (found === undefined) throw new Error(`Нет документа ${id}`);
  return found;
}
