async def seed(session: AsyncSession, only_new: bool = False) -> tuple[int, int, int]:
    """
    Загрузить зоны в переданную сессию.

    Возвращает количество добавленных, обновлённых и выведенных из игры.
    Сессию открывает вызывающий: так эту функцию можно проверить тестом, не
    трогая настоящую базу.
    """
    added = updated = retired = 0

    existing = {
        zone.name: zone for zone in (await session.execute(select(LocationZone))).scalars().all()
    }

    for spec in ZONES:
        zone = existing.get(spec.name)

        if zone is None:
            zone = LocationZone(name=spec.name, is_active=True)
            session.add(zone)
            added += 1
        elif only_new:
            continue
        else:
            zone.is_active = True
            updated += 1

        _apply(zone, spec)

    if not only_new:
        # Зона, убранная из списка, перестаёт попадаться в новых раундах.
        # Удалять её нельзя: на неё ссылаются уже сыгранные раунды
        wanted = {spec.name for spec in ZONES}
        for name, zone in existing.items():
            if name not in wanted and zone.is_active:
                zone.is_active = False
                retired += 1

    await session.commit()

    return added, updated, retired


async def seed_database(only_new: bool = False) -> tuple[int, int, int]:
    """Загрузить зоны в базу, указанную настройками."""
    async with AsyncSessionLocal() as session:
        return await seed(session, only_new=only_new)


def _apply(zone: LocationZone, spec: ZoneSpec) -> None:
    zone.description = spec.description
    zone.category = spec.category
    zone.tier = spec.tier
    zone.country = spec.country
    zone.region = spec.region
    zone.continent = spec.continent
    zone.tags = json.dumps(spec.tags, ensure_ascii=False)
    zone.polygon = WKTElement(spec.polygon_wkt(), srid=4326)


def main() -> None:
    parser = argparse.ArgumentParser(description="Загрузка игровых зон Location King")
    parser.add_argument(
        "--only-new",
        action="store_true",
        help="не трогать зоны, которые уже есть в базе",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)-8s %(message)s")

    added, updated, retired = asyncio.run(seed_database(only_new=args.only_new))
    logger.info(
        "Зоны загружены: добавлено %s, обновлено %s, выведено из игры %s, всего в списке %s",
        added,
        updated,
        retired,
        len(ZONES),
    )


if __name__ == "__main__":
    main()
