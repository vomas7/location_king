"""
Загрузка игровых зон в базу.

Запускается сколько угодно раз: зоны сопоставляются по имени, существующие
обновляются, новые добавляются. Зона, которой в списке больше нет, не
удаляется, а помечается неактивной — раунды, уже сыгранные в ней, должны
остаться читаемыми.

Зона описывается центром и радиусом, а не готовым полигоном: так список
читается и правится, а квадрат вокруг центра для выбора случайной точки ничем
не хуже нарисованного вручную контура.

Уровень партии — это свойство самой зоны, а не её категории. Категория
говорит, что игрок увидит (город, побережье, горы), а уровень — насколько это
место вообще возможно узнать. Из категории второе не выводится: Гамбург и
Сурабая оба «city», но первый называют с ходу, а второй не назовёт почти
никто.

    легко     — узнают по силуэту, даже не бывав там: Париж, Венеция, Манхэттен
    средне    — крупный город знакомой страны: Гамбург, Казань, Сиэтл
    сложно    — города, о которых знают мало, и обжитая местность без города
    хардкор   — дикая природа, где ориентиров нет вовсе

Радиус городской зоны ограничен пятью километрами: точка раунда берётся из
квадрата вокруг центра, и при виде в пятнадцать километров центр города
должен оставаться в кадре. Иначе «Париж» показывает безымянный пригород.

Дикая местность на большом зуме выглядит размытой мозаикой Landsat, поэтому
попадается только тем, кто выбрал хардкор осознанно.

    python scripts/seed.py
    python scripts/seed.py --only-new
"""

