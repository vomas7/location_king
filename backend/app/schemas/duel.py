"""Схемы подбора соперника."""

from pydantic import BaseModel


class DuelSearchView(BaseModel):
    """
    Состояние поиска.

    Либо число ищущих — его показывают у кнопки, — либо код найденной дуэли.
    Одновременно и то и другое не нужно: как только пара нашлась, считать
    очередь незачем.
    """

    #: Сколько человек ищет соперника прямо сейчас, вместе с самим игроком
    searching: int
    #: Код дуэли, если пара нашлась. Дальше игрок входит в неё как в комнату
    code: str | None


class DuelFormatView(BaseModel):
    """
    Условия дуэли. Одни и те же для всех и неизменяемые.

    Отдаются клиенту, чтобы он показал их до начала поиска, а не пересказывал
    своими словами то, что решает сервер.
    """

    rounds_total: int
    view_extent_km: float
    difficulty: str
    time_limit_seconds: int
