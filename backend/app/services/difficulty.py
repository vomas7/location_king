"""
Что означает уровень, кроме набора мест.

Раньше ширину кадра игрок выбирал сам, отдельным переключателем рядом с
уровнем. Это был самый непонятный элемент меню: «сорок километров» ничего не
говорит о том, будет ли трудно, а два независимых регулятора сложности легко
свести в бессмысленную пару — дикая природа в кадре на пять километров не
угадывается вообще никак.

Теперь кадр — свойство уровня. Он не усиливает сложность, а выравнивает её:
чем меньше в кадре рукотворных ориентиров, тем больше нужно контекста, чтобы
место вообще можно было прочитать. Париж узнают и по двадцати километрам, а
тайгу читают по излучине реки и хребту, и для них нужен масштаб.

Числа подобраны так, чтобы каждый уровень оставался играбельным. Их стоит
пересматривать по статистике промахов — `scripts/stats.py --only extent`.

Это заказ, а не точное значение: участок раунда — один тайл Web Mercator, и
его настоящая ширина зависит от широты. Кадр раунда получается ближайшим к
заказанному, и в базе лежит именно он.
"""

from app.models.enums import Difficulty

#: Сколько земли попадает в кадр на каждом уровне, в километрах
VIEW_EXTENT_KM: dict[str, float] = {
    Difficulty.EASY: 20.0,
    Difficulty.NORMAL: 30.0,
    Difficulty.HARD: 45.0,
    Difficulty.HARDCORE: 70.0,
}

#: Кадр партии без указанного уровня. Столько же, сколько у «средне»: это и
#: есть уровень по умолчанию
DEFAULT_VIEW_EXTENT_KM = VIEW_EXTENT_KM[Difficulty.NORMAL]


def view_extent_km(difficulty: str | None) -> float:
    """Ширина кадра для уровня. Неизвестный уровень получает кадр «средне»."""
    if difficulty is None:
        return DEFAULT_VIEW_EXTENT_KM

    return VIEW_EXTENT_KM.get(difficulty, DEFAULT_VIEW_EXTENT_KM)
