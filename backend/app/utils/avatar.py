"""
Аватарка игрока.

По умолчанию это не картинка, а два числа: форма узора и цвет. Рисует узор
клиент — сервер не должен знать, как узор выглядит, чтобы менять его вид без
миграций. Такая аватарка есть у каждого с первой минуты, её не нужно
выбирать, и хранить для неё нечего.

Кто хочет своё лицо, загружает картинку: тогда у аватарки появляется адрес,
и показывают её. Что с загруженным делает сервер — в app/services/avatars.py.
"""

#: Сколько всего форм и цветов. Клиент знает эти же числа и рисует по ним;
#: незнакомую форму он покажет первой, поэтому список можно расширять, не
#: дожидаясь обновления страниц у игроков
SHAPES = 6
COLORS = 6


def default_for(user_id: int) -> tuple[int, int]:
    """
    Аватарка, которая достаётся при регистрации.

    Выводится из идентификатора, поэтому у зарегистрировавшихся подряд она
    разная: одинаковая заглушка у всех означала бы, что аватарки нет.
    """
    return user_id % SHAPES, (user_id // SHAPES) % COLORS


def is_known(shape: int, color: int) -> bool:
    """Существует ли такая аватарка."""
    return 0 <= shape < SHAPES and 0 <= color < COLORS


def image_url(user_id: int, version: int) -> str | None:
    """
    Адрес загруженной аватарки. Ничего — если игрок ничего не загружал.

    Версия в адресе нужна затем, чтобы он менялся вместе с картинкой: без
    этого браузер неделю показывал бы прежнюю из кэша.
    """
    if version <= 0:
        return None

    return f"/api/avatars/{user_id}?v={version}"
