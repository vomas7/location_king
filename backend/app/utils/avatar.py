"""
Аватарка игрока.

Не картинка, а два числа: форма узора и цвет. Рисует узор клиент, поэтому
файлов нет вовсе — а значит, нет ни хранилища, ни обработки, ни модерации.
Это не экономия, а осознанный отказ: загруженную картинку видно в таблице
лидеров и в комнате, то есть это публикация, и отвечать за неё пришлось бы
владельцу игры.

Числа, а не готовая разметка, потому что рисование — дело клиента: сервер не
должен знать, как выглядит узор, чтобы менять его вид без миграций.
"""

#: Сколько всего форм и цветов. Клиент знает эти же числа и рисует по ним;
#: незнакомую форму он покажет первой, поэтому список можно расширять, не
#: дожидаясь обновления страниц у игроков
SHAPES = 6
COLORS = 6


def default_for(user_id: int) -> tuple[int, int]:
    """
    Аватарка, которая достаётся при регистрации.

    Выводится из идентификатора, поэтому у зарегистрировавшихся подряд она
    разная: одинаковая заглушка у всех означала бы, что аватарки нет.
    """
    return user_id % SHAPES, (user_id // SHAPES) % COLORS


def is_known(shape: int, color: int) -> bool:
    """Существует ли такая аватарка."""
    return 0 <= shape < SHAPES and 0 <= color < COLORS
