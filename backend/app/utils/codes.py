"""
Короткие коды, которые человек набирает руками.

Один алфавит на все такие коды: и комнату, и игрока диктуют голосом, и в обоих
случаях ноль от буквы «O» отличить на слух невозможно. Поэтому похожих друг на
друга символов в алфавите нет вовсе.
"""

import secrets

#: Ни нуля с «O», ни единицы с «I»: код набирают с голоса и переписывают от руки
ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
LENGTH = 6


def new_code() -> str:
    """Случайный код. Проверять, что он свободен, — дело вызывающего."""
    return "".join(secrets.choice(ALPHABET) for _ in range(LENGTH))
