"""
Рейтинг Эло.

Чистая арифметика: ни базы, ни игры. Рейтинг отвечает ровно на один вопрос —
кто кого обыграет, — и держится на одном условии: соперники играли одно и то
же. В дуэли оно выполнено, серия раундов у обоих общая, поэтому уровень,
масштаб и таймер сокращаются, и сравнивать можно кого угодно с кем угодно.

Средний промах на эту роль не годится, хотя и просится: он зависит от условий
партии сильнее, чем от игрока. На лёгком уровне по Европе он в десятки раз
меньше, чем на хардкоре по всему миру, — и рейтинг из него поставил бы наверх
того, кто выбрал условия помягче.
"""

#: С чего начинают все. Число само по себе ничего не значит, важна разница
START_RATING = 1000

#: Ниже рейтинг не опускается: бесконечная яма никому не помогает
MIN_RATING = 100

#: Разница рейтингов, при которой сильнейший берёт примерно девять партий из
#: десяти. Классическое значение Эло, менять его незачем
RATING_SCALE = 400

#: Насколько сильно одна дуэль двигает рейтинг. Новичку нужно быстро попасть
#: на своё место, поэтому первые дуэли двигают его вдвое сильнее
K_PLACEMENT = 40
K_SETTLED = 20
PLACEMENT_DUELS = 10


def k_factor(duels_played: int) -> int:
    """Шаг рейтинга: у новичка крупнее, чтобы он быстрее нашёл своё место."""
    return K_PLACEMENT if duels_played < PLACEMENT_DUELS else K_SETTLED


def expected(rating: int, opponent_rating: int) -> float:
    """Ожидаемая доля очков против соперника: от нуля до единицы."""
    return 1 / (1 + 10 ** ((opponent_rating - rating) / RATING_SCALE))


def updated(rating: int, opponent_rating: int, outcome: float, duels_played: int) -> int:
    """
    Рейтинг после дуэли.

    Результат — единица за победу, половина за ничью, ноль за поражение.
    Считается только исход, а не разрыв в очках: один удачный раунд качает
    разрыв сильно, а победу — нет, и рейтинг по разрыву было бы легче накрутить.
    """
    if not 0.0 <= outcome <= 1.0:
        raise ValueError("Исход дуэли — число от нуля до единицы")

    change = k_factor(duels_played) * (outcome - expected(rating, opponent_rating))
    return max(round(rating + change), MIN_RATING)
